@Language.component("financial_lemmatizer")
def _financial_lemmatizer(doc: Doc) -> Doc:
    for token in doc:
        lemma = LEMMA_OVERRIDES.get(token.text.lower())
        if lemma is not None:
            token.lemma_ = lemma
    return doc


@lru_cache
def get_nlp() -> Language | None:
    try:
        nlp = spacy.load("ru_core_news_md")
    except OSError:
        return None
    if "financial_lemmatizer" not in nlp.pipe_names:
        nlp.add_pipe("financial_lemmatizer", after="lemmatizer")
    return nlp


def model_available() -> bool:
    return get_nlp() is not None


class Lemmatizer:
    """Приводит токены текста к леммам."""

    def lemmatize(self, text: str) -> list[Token]:
        nlp = get_nlp()
        if nlp is None:
            return [Token(text=word, lemma=word.lower()) for word in text.split()]
        doc = nlp(text)
        return [Token(text=token.text, lemma=token.lemma_) for token in doc if not token.is_space]